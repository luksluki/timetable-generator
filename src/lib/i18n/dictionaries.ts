export type Locale = "id" | "en";

export const DEFAULT_LOCALE: Locale = "id";
export const LOCALE_COOKIE = "locale";

function lookup(locale: Locale, key: string): unknown {
  const parts = key.split(".");
  let cur: unknown = dictionary[locale];
  for (const p of parts) {
    if (cur && typeof cur === "object" && p in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[p];
    } else {
      cur = undefined;
      break;
    }
  }
  if (cur === undefined && locale !== "en") return lookup("en", key);
  return cur ?? key;
}

/** Translate a dotted key; may return a string, string[] or a function. */
export function t(locale: Locale, key: string): unknown {
  return lookup(locale, key);
}

/** Translate a dotted key that is expected to be a plain string. */
export function ts(locale: Locale, key: string): string {
  const v = lookup(locale, key);
  return typeof v === "string" ? v : key;
}

export function isValidLocale(v: string | undefined | null): v is Locale {
  return v === "id" || v === "en";
}
